import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";

/** Default log location, relative to the project root. */
export const LOG_REL = path.join("docs", "ai", "GEMINI_LOG.md");
const HEADER = "# Gemini log\n\nWritten by the zwilling MCP server. One entry per call, newest last.\n\n";
/**
 * Invisible marker before each entry. Answers are free-form markdown and may contain
 * `---` or `## ` themselves, so those can't be used to split entries reliably.
 * Old entries have no id: `<!-- zwilling:entry -->`.
 */
const MARKER_RE = /^<!-- zwilling:entry(?: id=([A-Za-z0-9-]+))? -->[ \t]*$/gm;
/** Marker text inside logged content is defused with a zero-width space, so it can't split entries. */
const MARKER_TEXT = "<!-- zwilling:";
const MARKER_ESCAPED = "<!-- zwilling\u200b:";
const PROMPT_PREVIEW_CHARS = 500;
const DETAILS_OPEN = "<details><summary>Full prompt</summary>";

/** Entry ids look like `g-20261113-a1b2c3`. */
export const ENTRY_ID_RE = /^g-\d{8}-[0-9a-f]{6}$/;

export interface LogEntry {
  /** Generated by appendEntry if missing. */
  id?: string;
  tool: string;
  model?: string;
  prompt: string;
  files: string[];
  /** Id of the entry this call followed up on. */
  followUp?: string;
  answer?: string;
  error?: string;
  date?: Date;
}

/** An entry read back from the log. */
export interface ParsedEntry {
  /** Undefined for entries written before ids existed. */
  id?: string;
  /** The entry's markdown as stored (without the marker). */
  text: string;
  tool?: string;
  model?: string;
  prompt: string;
  /** False if only a (possibly truncated) preview of the prompt is stored (old entries). */
  promptComplete: boolean;
  files: string[];
  followUp?: string;
  answer?: string;
  error?: string;
}

const pad = (n: number) => String(n).padStart(2, "0");
function stamp(d: Date): string {
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}`;
}

export function newEntryId(d: Date = new Date()): string {
  return `g-${d.getFullYear()}${pad(d.getMonth() + 1)}${pad(d.getDate())}-${crypto.randomBytes(3).toString("hex")}`;
}

const escape = (s: string) => s.split(MARKER_TEXT).join(MARKER_ESCAPED);
const unescape = (s: string) => s.split(MARKER_ESCAPED).join(MARKER_TEXT);
const oneLine = (s: string) => s.replace(/\s+/g, " ").trim();

/** A backtick fence longer than any backtick run in `s`, so `s` can't close it. */
function fenceFor(s: string): string {
  const longest = Math.max(0, ...(s.match(/`+/g) ?? []).map((m) => m.length));
  return "`".repeat(Math.max(3, longest + 1));
}

export function formatEntry(e: LogEntry): string {
  const date = e.date ?? new Date();
  const id = e.id ?? newEntryId(date);
  const flat = oneLine(e.prompt);
  const preview = flat.length > PROMPT_PREVIEW_CHARS ? flat.slice(0, PROMPT_PREVIEW_CHARS) + "…" : flat;
  const lines = [
    `<!-- zwilling:entry id=${id} -->`,
    `## ${stamp(date)} · ${e.tool} · model: ${oneLine(e.model || "default")} · id: ${id}`,
    `**Prompt:** ${escape(preview)}`,
  ];
  // The preview line is exact for short single-line prompts; otherwise store the full prompt.
  if (preview !== e.prompt) {
    const body = escape(e.prompt);
    const fence = fenceFor(body);
    lines.push(DETAILS_OPEN, "", fence + "text", body, fence, "", "</details>", "");
  }
  lines.push(`**Files:** ${e.files.length ? e.files.join(", ") : "none"}`);
  if (e.followUp) lines.push(`**Follow-up of:** ${e.followUp}`);
  if (e.error !== undefined) lines.push(`**Error:**`, escape(e.error));
  else lines.push(`**Answer:**`, escape(e.answer ?? ""));
  lines.push("---", "", "");
  return lines.join("\n");
}

/** Parse one entry's markdown (marker removed, trimmed). Lenient with old-format entries. */
export function parseEntry(text: string, id?: string): ParsedEntry {
  const lines = text.split("\n");
  const head = /^## .+? · (.+?) · model: (.+?)(?: · id: \S+)?$/.exec(lines[0] ?? "");
  const entry: ParsedEntry = {
    id,
    text,
    tool: head?.[1],
    model: head?.[2],
    prompt: "",
    promptComplete: false,
    files: [],
  };

  let i = lines.findIndex((l) => l.startsWith("**Prompt:** "));
  if (i < 0) return entry;
  // Preview runs until the Files line or the full-prompt block (old previews may span lines).
  let j = i;
  while (j < lines.length && !lines[j].startsWith("**Files:** ") && lines[j] !== DETAILS_OPEN) j++;
  const preview = lines.slice(i, j).join("\n").slice("**Prompt:** ".length);
  entry.prompt = unescape(preview);
  // New entries store the full prompt whenever the preview differs; old ones only a 500-char preview.
  entry.promptComplete = !!id || !preview.endsWith("…");

  if (lines[j] === DETAILS_OPEN) {
    let k = j + 1;
    while (k < lines.length && !lines[k].startsWith("```")) k++;
    const fence = (lines[k] ?? "").replace(/text$/, "");
    const end = lines.indexOf(fence, k + 1);
    if (fence && end > k) {
      entry.prompt = unescape(lines.slice(k + 1, end).join("\n"));
      entry.promptComplete = true;
      j = end + 1;
    }
    while (j < lines.length && !lines[j].startsWith("**Files:** ")) j++;
  }

  if (j >= lines.length) return entry;
  const files = lines[j].slice("**Files:** ".length);
  entry.files = files === "none" ? [] : files.split(", ");
  j++;
  if (lines[j]?.startsWith("**Follow-up of:** ")) {
    entry.followUp = lines[j].slice("**Follow-up of:** ".length);
    j++;
  }
  const kind = lines[j];
  if (kind === "**Answer:**" || kind === "**Error:**") {
    let rest = lines.slice(j + 1).join("\n");
    if (rest === "---") rest = "";
    else if (rest.endsWith("\n---")) rest = rest.slice(0, -4);
    if (kind === "**Answer:**") entry.answer = unescape(rest);
    else entry.error = unescape(rest);
  }
  return entry;
}

function isInside(root: string, p: string): boolean {
  const rel = path.relative(root, p);
  return rel !== "" && !path.isAbsolute(rel) && rel !== ".." && !rel.startsWith(".." + path.sep);
}

/** Absolute log path for a root-relative `rel`; throws if it leaves the root or points into .git/. */
export function resolveLogPath(root: string, rel: string = LOG_REL): string {
  const abs = path.resolve(root, rel);
  if (!isInside(root, abs)) throw new Error(`Log path must stay inside the project root: ${rel}`);
  if (path.relative(root, abs).split(path.sep).includes(".git")) throw new Error(`Log path must not be inside .git/: ${rel}`);
  return abs;
}

/** Follow symlinks in the log's directory and make sure it still is inside the root. */
async function checkReal(root: string, file: string): Promise<void> {
  const dir = await fs.realpath(path.dirname(file));
  const realRoot = await fs.realpath(root);
  if (dir !== realRoot && !isInside(realRoot, dir)) throw new Error(`Log directory escapes the project root (via symlink): ${dir}`);
}

/** Per-file write queue, so parallel calls append whole entries one after another. */
const queues = new Map<string, Promise<unknown>>();
function serialized<T>(key: string, fn: () => Promise<T>): Promise<T> {
  const prev = queues.get(key) ?? Promise.resolve();
  const next = prev.then(fn, fn);
  const tail = next.catch(() => {});
  queues.set(key, tail);
  tail.then(() => {
    if (queues.get(key) === tail) queues.delete(key);
  });
  return next;
}

/** Append an entry and return its id. */
export async function appendEntry(root: string, e: LogEntry, rel: string = LOG_REL): Promise<string> {
  const file = resolveLogPath(root, rel);
  const date = e.date ?? new Date();
  const id = e.id ?? newEntryId(date);
  const text = formatEntry({ ...e, id, date });
  await serialized(file, async () => {
    await fs.mkdir(path.dirname(file), { recursive: true });
    await checkReal(root, file);
    // "wx" creates the file with the header only if it doesn't exist yet.
    await fs.writeFile(file, HEADER, { flag: "wx" }).catch((err) => {
      if (err.code !== "EEXIST") throw err;
    });
    await fs.appendFile(file, text);
  });
  return id;
}

/** All entries, oldest first, or null if the log doesn't exist yet. */
export async function readEntries(root: string, rel: string = LOG_REL): Promise<ParsedEntry[] | null> {
  const file = resolveLogPath(root, rel);
  let text: string;
  try {
    await checkReal(root, file);
    text = await fs.readFile(file, "utf8");
  } catch (err: any) {
    if (err.code === "ENOENT") return null;
    throw err;
  }
  const marks = [...text.matchAll(MARKER_RE)];
  return marks.map((m, n) => {
    const start = m.index! + m[0].length;
    const end = n + 1 < marks.length ? marks[n + 1].index! : text.length;
    return parseEntry(text.slice(start, end).trim(), m[1]);
  });
}

/** The entry with this id, or undefined. */
export async function findEntry(root: string, id: string, rel: string = LOG_REL): Promise<ParsedEntry | undefined> {
  return (await readEntries(root, rel))?.find((e) => e.id === id);
}

/** The last `n` entries' markdown, oldest first, or null if the log doesn't exist yet. */
export async function readLastEntries(root: string, n: number, rel: string = LOG_REL): Promise<string[] | null> {
  const entries = await readEntries(root, rel);
  if (!entries) return null;
  return n > 0 ? entries.slice(-n).map((e) => e.text) : [];
}
